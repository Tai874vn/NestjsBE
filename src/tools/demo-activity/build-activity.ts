/**
 * Demo activity for the seeded accounts: connections, feed posts with likes and comments, applications to
 * hiring posts, hires and reviews of portfolio services, saved items and chats.
 *
 * In simple words: the people, resumes and hiring posts already come from the trained data (ESCO occupation,
 * years, the AI level the model gave them). This file decides who interacts with whom FROM those facts, so the
 * whole site tells one story:
 *   - people connect with others in the same or a related occupation (ESCO "related" list, overlap >= 0.25);
 *   - candidates apply to posts for their occupation (or a related one) at a level close to theirs;
 *     the recruiter accepts the best fits, reviews some, and rejects the weakest;
 *   - recruiters chat with the people they accepted or are reviewing;
 *   - recruiters hire portfolio services in the occupations they hire for, and review the finished ones.
 * All wording comes from fixed templates filled with those facts; no text is generated by an AI model.
 *
 * It is a pure function (same input -> same output, no database): prisma/seed-activity.ts reads the
 * database, calls buildActivity, and writes the result.
 */

export const LEVELS = ['Junior', 'Mid', 'Senior'] as const;
export type Level = (typeof LEVELS)[number];

export type Person = {
  id: number;
  name: string;
  kind: 'candidate' | 'recruiter';
  /** ESCO occupation code from the resume; null for recruiters. */
  occupation: string | null;
  /** The AI level of the resume; null when there is none. */
  level: Level | null;
  /** Years in the occupation (main years from the resume's jobs). */
  years: number;
  skills: string[];
  location: string;
  discoverable: boolean;
  company: string | null;
};

export type HiringPostFact = {
  id: number;
  recruiterId: number;
  title: string;
  occupationCode: string | null;
  level: Level | null;
  yearsRequired: number;
  skills: string[];
  location: string;
  employmentType: string;
};

export type ServiceFact = {
  id: number;
  creatorId: number;
  title: string;
  summary: string;
  description: string;
};

export type ActivityInput = {
  people: Person[];
  hiringPosts: HiringPostFact[];
  services: ServiceFact[];
  /** ESCO relatedness: code -> (other code -> overlap). */
  related: Map<string, Map<string, number>>;
  occupationTitle: (code: string) => string;
  now: Date;
  seed?: number;
};

export type ApplicationStatus =
  | 'APPLIED'
  | 'REVIEWING'
  | 'ACCEPTED'
  | 'REJECTED'
  | 'WITHDRAWN';

export type Activity = {
  joinedAt: Map<number, Date>;
  hiringPostCreatedAt: Map<number, Date>;
  serviceCreatedAt: Map<number, Date>;
  connections: Array<{
    requesterId: number;
    recipientId: number;
    status: 'PENDING' | 'ACCEPTED';
    createdAt: Date;
    updatedAt: Date;
  }>;
  applications: Array<{
    hiringPostId: number;
    applicantId: number;
    status: ApplicationStatus;
    coverLetter: string;
    createdAt: Date;
    updatedAt: Date;
  }>;
  feedPosts: Array<{
    authorId: number;
    content: string;
    createdAt: Date;
    likes: Array<{ userId: number; createdAt: Date }>;
    comments: Array<{
      authorId: number;
      content: string;
      createdAt: Date;
      replyTo?: number;
    }>;
    savedBy: Array<{ userId: number; createdAt: Date }>;
  }>;
  hires: Array<{
    jobId: number;
    hirerId: number;
    hiredAt: Date;
    completed: boolean;
    review: { content: string; rating: number; commentedAt: Date } | null;
  }>;
  savedJobs: Array<{ userId: number; jobId: number; createdAt: Date }>;
  chats: Array<{
    members: [number, number];
    createdAt: Date;
    messages: Array<{ senderId: number; content: string; createdAt: Date }>;
  }>;
};

const DAY = 86_400_000;
const HOUR = 3_600_000;
const RELATED_FROM = 0.25;

/** A small seeded random generator (mulberry32), so every run with the same seed gives the same activity. */
export function randomGenerator(seed: number) {
  let state = seed >>> 0;
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
  return {
    next,
    chance: (probability: number) => next() < probability,
    int: (min: number, max: number) =>
      min + Math.floor(next() * (max - min + 1)),
    pick: <T>(items: readonly T[]): T =>
      items[Math.floor(next() * items.length)],
    shuffle: <T>(items: readonly T[]): T[] => {
      const copy = [...items];
      for (let index = copy.length - 1; index > 0; index -= 1) {
        const other = Math.floor(next() * (index + 1));
        [copy[index], copy[other]] = [copy[other], copy[index]];
      }
      return copy;
    },
  };
}
type Random = ReturnType<typeof randomGenerator>;

/** How close two occupations are: 1 the same, the ESCO overlap when related, 0.3 the same ISCO unit group. */
export function occupationFit(
  first: string | null,
  second: string | null,
  related: ActivityInput['related'],
) {
  if (!first || !second) return 0;
  if (first === second) return 1;
  const overlap =
    related.get(first)?.get(second) ?? related.get(second)?.get(first) ?? 0;
  if (overlap >= RELATED_FROM) return overlap;
  return first.slice(0, 4) === second.slice(0, 4) ? 0.3 : 0;
}

export function levelGap(first: Level | null, second: Level | null) {
  if (!first || !second) return 1;
  return Math.abs(LEVELS.indexOf(first) - LEVELS.indexOf(second));
}

/**
 * How well a candidate fits a hiring post: the occupation fit, minus 0.3 per level step apart, minus 0.2 when
 * they have clearly fewer years than asked for. Candidates at 0.25 or more apply.
 */
export function applicationFit(
  candidate: Person,
  post: HiringPostFact,
  related: ActivityInput['related'],
) {
  const occupation = occupationFit(
    candidate.occupation,
    post.occupationCode,
    related,
  );
  if (occupation === 0) return 0;
  const shortOfYears = candidate.years < post.yearsRequired - 1 ? 0.2 : 0;
  return (
    occupation - 0.3 * levelGap(candidate.level, post.level) - shortOfYears
  );
}

const firstName = (person: Person) => person.name.split(' ')[0];
const years = (value: number) => {
  const rounded = Math.max(1, Math.round(value));
  return rounded === 1 ? '1 year' : `${rounded} years`;
};
const list = (items: string[]) =>
  items.length <= 1
    ? (items[0] ?? '')
    : `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`;
const between = (random: Random, from: Date, to: Date) =>
  new Date(
    from.getTime() + random.next() * Math.max(0, to.getTime() - from.getTime()),
  );
const after = (
  random: Random,
  from: Date,
  minHours: number,
  maxHours: number,
  cap: Date,
) =>
  new Date(
    Math.min(
      cap.getTime(),
      from.getTime() +
        (minHours + random.next() * (maxHours - minHours)) * HOUR,
    ),
  );

export function buildActivity(input: ActivityInput): Activity {
  const random = randomGenerator(input.seed ?? 2026);
  const { now, related } = input;
  const people = new Map(input.people.map((person) => [person.id, person]));
  const candidates = input.people.filter(
    (person) => person.kind === 'candidate',
  );
  const recruiters = input.people.filter(
    (person) => person.kind === 'recruiter',
  );
  const title = (code: string | null) =>
    code ? input.occupationTitle(code) : 'professional';
  const ago = (days: number) => new Date(now.getTime() - days * DAY);

  // 1. A timeline: people joined 50-90 days ago; their services and hiring posts came after.
  const joinedAt = new Map<number, Date>();
  for (const person of input.people)
    joinedAt.set(person.id, ago(random.int(50, 90) + random.next()));
  const serviceCreatedAt = new Map<number, Date>();
  for (const service of input.services) {
    serviceCreatedAt.set(
      service.id,
      between(random, joinedAt.get(service.creatorId) ?? ago(60), ago(30)),
    );
  }
  const hiringPostCreatedAt = new Map<number, Date>();
  for (const post of input.hiringPosts) {
    hiringPostCreatedAt.set(post.id, between(random, ago(35), ago(1)));
  }

  // 2. Applications: candidates whose occupation and level fit the post.
  const applications: Activity['applications'] = [];
  for (const post of input.hiringPosts) {
    const posted = hiringPostCreatedAt.get(post.id)!;
    const ageDays = (now.getTime() - posted.getTime()) / DAY;
    const fits = candidates
      .map((candidate) => ({
        candidate,
        fit: applicationFit(candidate, post, related),
      }))
      .filter((entry) => entry.fit >= 0.25)
      .sort((a, b) => b.fit - a.fit || a.candidate.id - b.candidate.id);
    const chosen = fits.slice(0, Math.min(fits.length, random.int(2, 8)));
    let accepted = false;
    for (const [rank, { candidate, fit }] of chosen.entries()) {
      const createdAt = between(
        random,
        posted,
        new Date(Math.min(now.getTime(), posted.getTime() + 10 * DAY)),
      );
      let status: ApplicationStatus = 'APPLIED';
      if (ageDays > 7) {
        if (!accepted && rank === 0 && fit >= 0.9 && random.chance(0.6)) {
          status = 'ACCEPTED';
          accepted = true;
        } else if (fit < 0.5 && random.chance(0.7)) status = 'REJECTED';
        else if (rank <= 2 && random.chance(0.6)) status = 'REVIEWING';
        else if (random.chance(0.07)) status = 'WITHDRAWN';
      } else if (ageDays > 2 && rank <= 1 && random.chance(0.5))
        status = 'REVIEWING';
      const updatedAt =
        status === 'APPLIED'
          ? createdAt
          : after(random, createdAt, 12, 96, now);
      applications.push({
        hiringPostId: post.id,
        applicantId: candidate.id,
        status,
        coverLetter: coverLetter(random, candidate, post, title),
        createdAt,
        updatedAt,
      });
    }
  }

  // 3. Connections: same or related occupation, plus recruiters with the people they shortlisted.
  const connections = new Map<string, Activity['connections'][number]>();
  const connect = (
    requesterId: number,
    recipientId: number,
    earliest: Date,
    acceptedChance: number,
  ) => {
    const key = [requesterId, recipientId].sort((a, b) => a - b).join(':');
    if (requesterId === recipientId || connections.has(key)) return;
    const start = new Date(
      Math.max(
        earliest.getTime(),
        joinedAt.get(requesterId)!.getTime(),
        joinedAt.get(recipientId)!.getTime(),
      ),
    );
    const createdAt = between(random, start, now);
    const status = random.chance(acceptedChance) ? 'ACCEPTED' : 'PENDING';
    connections.set(key, {
      requesterId,
      recipientId,
      status,
      createdAt,
      updatedAt:
        status === 'ACCEPTED'
          ? after(random, createdAt, 1, 48, now)
          : createdAt,
    });
  };
  for (const candidate of candidates) {
    const peers = candidates.filter(
      (other) =>
        other.id !== candidate.id &&
        occupationFit(candidate.occupation, other.occupation, related) >=
          RELATED_FROM,
    );
    for (const peer of random.shuffle(peers).slice(0, random.int(1, 4)))
      connect(candidate.id, peer.id, ago(90), 0.8);
    if (random.chance(0.3))
      connect(candidate.id, random.pick(candidates).id, ago(90), 0.6);
  }
  const postById = new Map(input.hiringPosts.map((post) => [post.id, post]));
  for (const application of applications) {
    if (
      application.status === 'ACCEPTED' ||
      application.status === 'REVIEWING'
    ) {
      connect(
        postById.get(application.hiringPostId)!.recruiterId,
        application.applicantId,
        application.updatedAt,
        0.85,
      );
    }
  }
  const friends = new Map<number, number[]>();
  for (const connection of connections.values()) {
    if (connection.status !== 'ACCEPTED') continue;
    friends.set(connection.requesterId, [
      ...(friends.get(connection.requesterId) ?? []),
      connection.recipientId,
    ]);
    friends.set(connection.recipientId, [
      ...(friends.get(connection.recipientId) ?? []),
      connection.requesterId,
    ]);
  }

  // 4. Feed posts, with likes from connections and comments that fit the kind of post.
  const servicesBy = new Map<number, ServiceFact[]>();
  for (const service of input.services)
    servicesBy.set(service.creatorId, [
      ...(servicesBy.get(service.creatorId) ?? []),
      service,
    ]);
  const applicantsOf = new Map<number, Activity['applications']>();
  for (const application of applications) {
    applicantsOf.set(application.hiringPostId, [
      ...(applicantsOf.get(application.hiringPostId) ?? []),
      application,
    ]);
  }
  const feedPosts: Activity['feedPosts'] = [];
  const addPost = (
    authorId: number,
    content: string,
    createdAt: Date,
    comments: Array<{ authorId: number; content: string; notBefore?: Date }>,
    reply: string | null,
  ) => {
    const audience = random.shuffle(friends.get(authorId) ?? []);
    const likes = audience
      .filter(() => random.chance(0.55))
      .map((userId) => ({
        userId,
        createdAt: after(random, createdAt, 0.2, 72, now),
      }));
    const timed = comments
      .filter((comment) => comment.authorId !== authorId)
      .map(({ notBefore, ...comment }) => ({
        ...comment,
        createdAt: after(
          random,
          notBefore && notBefore > createdAt ? notBefore : createdAt,
          0.5,
          60,
          now,
        ),
      }))
      .sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime());
    const withReply: Activity['feedPosts'][number]['comments'] = [...timed];
    if (reply && timed.length && random.chance(0.6)) {
      withReply.push({
        authorId,
        content: reply,
        createdAt: after(random, timed[0].createdAt, 0.5, 24, now),
        replyTo: 0,
      });
    }
    feedPosts.push({
      authorId,
      content,
      createdAt,
      likes,
      comments: withReply,
      savedBy: [],
    });
    return feedPosts[feedPosts.length - 1];
  };
  const commenters = (authorId: number, count: number) =>
    random.shuffle(friends.get(authorId) ?? []).slice(0, count);

  for (const candidate of candidates) {
    const occupation = title(candidate.occupation);
    const kinds = random
      .shuffle(['project', 'milestone', 'learning', 'open'] as const)
      .slice(0, random.int(0, 2));
    for (const kind of kinds) {
      const createdAt = between(random, joinedAt.get(candidate.id)!, ago(0.2));
      const skill = candidate.skills.length
        ? random.pick(candidate.skills)
        : null;
      if (kind === 'project') {
        const service = random.pick(servicesBy.get(candidate.id) ?? [null]);
        if (!service) continue;
        const result = /Result: ([^.]+)\./.exec(service.description)?.[1];
        addPost(
          candidate.id,
          `Wrapped up "${service.title}"${builtWith(service)}.${result ? ` Result: ${result}.` : ''} Happy to share what I learned.`,
          createdAt,
          commenters(candidate.id, random.int(0, 3)).map((id, index) => ({
            authorId: id,
            content: [
              `Nice work, ${firstName(candidate)}! How long did it take?`,
              skill
                ? `Did you use ${skill} for the main part?`
                : 'What was the hardest part?',
              'Great result. Would love to read a write-up.',
            ][index % 3],
          })),
          `Thanks! About ${random.int(3, 10)} weeks${skill ? `, mostly with ${skill}` : ''}.`,
        );
      } else if (kind === 'milestone' && candidate.years >= 1) {
        addPost(
          candidate.id,
          `${years(candidate.years)} as a ${occupation} this month. Biggest lesson so far: ${random.pick(LESSONS[candidate.level ?? 'Mid'])}`,
          createdAt,
          commenters(candidate.id, random.int(1, 3)).map((id, index) => ({
            authorId: id,
            content: [
              `Congrats, ${firstName(candidate)}!`,
              'Well deserved.',
              'So true about that lesson.',
            ][index % 3],
          })),
          'Thank you all!',
        );
      } else if (kind === 'learning' && skill) {
        addPost(
          candidate.id,
          `Spending this week going deeper into ${skill}. Any good resources for using it in ${occupation} work?`,
          createdAt,
          commenters(candidate.id, random.int(0, 2)).map((id, index) => ({
            authorId: id,
            content: [
              `The official ${skill} documentation is a good start, then a small real project.`,
              `I learned ${skill} by rebuilding something I use at work. Worth trying.`,
            ][index % 2],
          })),
          'Thanks, I will try that.',
        );
      } else if (kind === 'open' && candidate.discoverable) {
        const top = candidate.skills.slice(0, 3);
        const post = addPost(
          candidate.id,
          `Open to new ${occupation} roles in ${candidate.location} or remote. ${years(candidate.years)} of experience${top.length ? `, mostly with ${list(top)}` : ''}. Messages welcome.`,
          createdAt,
          [],
          null,
        );
        // Recruiters hiring for this occupation notice and save the post.
        for (const recruiter of recruiters) {
          const hiring = input.hiringPosts.some(
            (item) =>
              item.recruiterId === recruiter.id &&
              occupationFit(
                item.occupationCode,
                candidate.occupation,
                related,
              ) >= 0.5,
          );
          if (hiring && random.chance(0.6)) {
            post.savedBy.push({
              userId: recruiter.id,
              createdAt: after(random, createdAt, 1, 72, now),
            });
          }
        }
      }
    }
  }

  for (const post of input.hiringPosts) {
    if (!random.chance(0.7)) continue;
    const recruiter = people.get(post.recruiterId)!;
    const createdAt = after(
      random,
      hiringPostCreatedAt.get(post.id)!,
      0.1,
      6,
      now,
    );
    const applied = (applicantsOf.get(post.id) ?? []).filter(
      (application) => application.status !== 'WITHDRAWN',
    );
    const comments = [
      ...applied.slice(0, 2).map((application) => ({
        authorId: application.applicantId,
        notBefore: application.createdAt,
        content: random.pick([
          'Applied!',
          'Just sent my application.',
          'Applied, looking forward to hearing back.',
        ]),
      })),
      ...(random.chance(0.4)
        ? [
            {
              authorId: random.pick(candidates).id,
              content: 'Is remote work possible for this role?',
            },
          ]
        : []),
    ];
    const feedPost = addPost(
      post.recruiterId,
      `${recruiter.company ? `${recruiter.company} is hiring` : 'We are hiring'}: ${post.title} in ${post.location} (${post.employmentType}). ` +
        `Looking for ${post.yearsRequired === 0 ? 'people starting out' : `at least ${years(post.yearsRequired)} of experience`}` +
        `${post.skills.length ? ` with ${list(post.skills.slice(0, 3))}` : ''}. Details and applications: /hiring-posts/${post.id}`,
      createdAt,
      comments,
      `Thanks! ${post.location} first, with some remote days. Apply on the post and we will reply within a week.`,
    );
    for (const candidate of candidates) {
      if (
        occupationFit(candidate.occupation, post.occupationCode, related) >=
          0.5 &&
        random.chance(0.25)
      ) {
        feedPost.savedBy.push({
          userId: candidate.id,
          createdAt: after(random, createdAt, 1, 96, now),
        });
      }
    }
  }
  feedPosts.sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime());

  // 5. Hires: recruiters (and a few candidates) hire services in the occupations they work with.
  const hires: Activity['hires'] = [];
  const savedJobs: Activity['savedJobs'] = [];
  const hirers = [
    ...recruiters,
    ...candidates.filter(() => random.chance(0.12)),
  ];
  for (const hirer of hirers) {
    const wanted =
      hirer.kind === 'recruiter'
        ? input.hiringPosts
            .filter((post) => post.recruiterId === hirer.id)
            .map((post) => post.occupationCode)
        : [hirer.occupation];
    const options = input.services.filter((service) => {
      const creator = people.get(service.creatorId);
      return (
        creator &&
        creator.id !== hirer.id &&
        wanted.some(
          (code) => occupationFit(code, creator.occupation, related) >= 0.3,
        )
      );
    });
    const shuffled = random.shuffle(options);
    for (const service of shuffled.slice(
      0,
      random.int(
        hirer.kind === 'recruiter' ? 1 : 0,
        hirer.kind === 'recruiter' ? 3 : 1,
      ),
    )) {
      const hiredAt = between(
        random,
        serviceCreatedAt.get(service.id)!,
        ago(1),
      );
      const completed =
        now.getTime() - hiredAt.getTime() > 10 * DAY && random.chance(0.7);
      const creator = people.get(service.creatorId)!;
      const rating = random.pick(RATINGS[creator.level ?? 'Mid']);
      const skill = creator.skills.length
        ? random.pick(creator.skills)
        : 'the work';
      const review =
        completed && random.chance(0.8)
          ? {
              rating,
              commentedAt: after(random, hiredAt, 24 * 7, 24 * 12, now),
              content: random.pick(REVIEWS[rating])(
                service.title,
                skill,
                firstName(creator),
              ),
            }
          : null;
      hires.push({
        jobId: service.id,
        hirerId: hirer.id,
        hiredAt,
        completed,
        review,
      });
    }
    for (const service of shuffled.slice(3, 3 + random.int(0, 2))) {
      savedJobs.push({
        userId: hirer.id,
        jobId: service.id,
        createdAt: between(random, serviceCreatedAt.get(service.id)!, now),
      });
    }
  }

  // 6. Chats: recruiters with accepted and some reviewed applicants, and a few between connected peers.
  const chats = new Map<string, Activity['chats'][number]>();
  const chatWith = (first: number, second: number, start: Date) => {
    const key = [first, second].sort((a, b) => a - b).join(':');
    const chat = chats.get(key) ?? {
      members: [first, second] as [number, number],
      createdAt: start,
      messages: [],
    };
    chats.set(key, chat);
    return chat;
  };
  for (const application of applications) {
    const reviewing = application.status === 'REVIEWING' && random.chance(0.5);
    if (application.status !== 'ACCEPTED' && !reviewing) continue;
    const post = postById.get(application.hiringPostId)!;
    const candidate = people.get(application.applicantId)!;
    const chat = chatWith(
      post.recruiterId,
      candidate.id,
      application.updatedAt,
    );
    const skill =
      post.skills.find((item) => candidate.skills.includes(item)) ??
      post.skills[0] ??
      'this kind of work';
    const lines: Array<[number, string]> =
      application.status === 'ACCEPTED'
        ? [
            [
              post.recruiterId,
              `Hi ${firstName(candidate)}, thanks for applying to ${post.title}. Your ${years(candidate.years)} as a ${title(candidate.occupation)} stood out. Do you have time for a 30-minute call this week?`,
            ],
            [candidate.id, `Thank you! Thursday afternoon works for me.`],
            [
              post.recruiterId,
              `Great, I have sent an invite for Thursday at 3 pm.`,
            ],
            [
              post.recruiterId,
              `Thanks for the call today. We would like to offer you the ${post.title} role. I will send the details by email.`,
            ],
            [
              candidate.id,
              `That is great news, thank you! I will read it tonight.`,
            ],
          ]
        : [
            [
              post.recruiterId,
              `Hi ${firstName(candidate)}, we are reviewing your application for ${post.title}. Quick question: how much of your recent work has been with ${skill}?`,
            ],
            [
              candidate.id,
              `Hi! Most of my last ${years(Math.max(1, Math.min(candidate.years, 3)))}. Happy to show examples.`,
            ],
            ...(random.chance(0.5)
              ? [
                  [
                    post.recruiterId,
                    'Thanks, that helps. We will get back to you this week.',
                  ] as [number, string],
                ]
              : []),
          ];
    let at = application.updatedAt;
    for (const [senderId, content] of lines) {
      at = after(random, at, 0.2, 30, now);
      chat.messages.push({ senderId, content, createdAt: at });
    }
  }
  const peerPairs = random
    .shuffle(
      [...connections.values()].filter(
        (connection) =>
          connection.status === 'ACCEPTED' &&
          people.get(connection.requesterId)!.kind === 'candidate' &&
          people.get(connection.recipientId)!.kind === 'candidate',
      ),
    )
    .slice(0, 15);
  for (const pair of peerPairs) {
    const [first, second] = [
      people.get(pair.requesterId)!,
      people.get(pair.recipientId)!,
    ];
    const chat = chatWith(first.id, second.id, pair.updatedAt);
    const skill =
      second.skills.find((item) => first.skills.includes(item)) ??
      second.skills[0] ??
      'your stack';
    let at = pair.updatedAt;
    for (const [senderId, content] of [
      [
        first.id,
        `Hi ${firstName(second)}, thanks for connecting! I saw you work with ${skill} too.`,
      ],
      [second.id, `Hi! Yes, every day. Are you using it at work?`],
      [
        first.id,
        `Mostly on side projects for now. Mind if I ask you a few questions later?`,
      ],
    ] as Array<[number, string]>) {
      at = after(random, at, 0.3, 20, now);
      chat.messages.push({ senderId, content, createdAt: at });
    }
  }

  return {
    joinedAt,
    hiringPostCreatedAt,
    serviceCreatedAt,
    connections: [...connections.values()],
    applications,
    feedPosts,
    hires,
    savedJobs,
    chats: [...chats.values()].filter((chat) => chat.messages.length),
  };
}

/** ", built with GitHub, Redis" from a summary like "Admin dashboard, built with GitHub, Redis." */
function builtWith(service: ServiceFact) {
  const match = /,( built with .+?)\.?$/.exec(service.summary);
  return match ? `,${match[1]}` : '';
}

function coverLetter(
  random: Random,
  candidate: Person,
  post: HiringPostFact,
  title: (code: string | null) => string,
) {
  const shared = post.skills
    .filter((skill) => candidate.skills.includes(skill))
    .slice(0, 3);
  const sameOccupation = candidate.occupation === post.occupationCode;
  const opening = random.pick([
    `Hi, I'm ${firstName(candidate)}.`,
    `Hello, my name is ${candidate.name}.`,
    `Hi! ${firstName(candidate)} here.`,
  ]);
  const experience = `I have ${years(candidate.years)} of experience as a ${title(candidate.occupation)}`;
  const skills = shared.length
    ? `, and I use ${list(shared)} in my daily work.`
    : '.';
  const fit = sameOccupation
    ? `The ${post.title} role is close to what I do now.`
    : `I would like to move into ${title(post.occupationCode)} work, and much of what I do already overlaps.`;
  return `${opening} ${experience}${skills} ${fit} Happy to talk whenever suits you.`;
}

