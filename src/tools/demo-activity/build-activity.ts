/**
 * Demo activity for the seeded accounts: connections, feed posts with likes and comments, applications to
 * hiring posts, hires and reviews of portfolio services, saved items and chats.
 *
 * In simple words: the people, resumes and hiring posts already come from the trained data (ESCO occupation,
 * years, the AI level the model gave them). This file decides who interacts with whom FROM those facts, so the
 * whole site tells one story:
 *   - people connect with others in the same or a related occupation (ESCO "related" list, overlap >= 0.25);
 *   - candidates apply to posts for their occupation (or a related one) at a level close to theirs;
 *     the recruiter shortlists some, interviews a part of them, sends a few offers, hires the best fits and
 *     rejects the weakest; every step leaves an event, an interview row or an offer note, like the real app;
 *   - recruiters chat with the people they hired or are reviewing;
 *   - recruiters hire portfolio services in the occupations they hire for, and review the finished ones.
 * All wording comes from fixed templates filled with those facts; no text is generated by an AI model.
 *
 * It is a pure function (same input -> same output, no database): prisma/seed-activity.ts reads the
 * database, calls buildActivity, and writes the result.
 */

