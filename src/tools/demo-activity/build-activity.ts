/**
 * Build the complete demo activity for a seeded dataset.
 * Keep these six steps in this exact order: each step depends on dates/records from earlier steps,
 * and they share one seeded random generator so the order keeps the output deterministic.
 */
export function buildActivity(input: ActivityInput): Activity {
  const ctx = createActivityContext(input);

  // 1. Place account join dates, service dates and hiring post dates across the last 90 days.
  const { joinedAt, serviceCreatedAt, hiringPostCreatedAt } =
    buildTimeline(ctx);

  // 2. Match candidates to hiring posts, advance shortlisted ones, set openings, and fill history.
  const { applications, openings } = buildHiringActivity(
    ctx,
    hiringPostCreatedAt,
  );

  // 3. Connect peers by occupation and connect recruiters with the applicants they shortlisted.
  const { connections, friends } = buildConnections(
    ctx,
    joinedAt,
    applications,
  );

  // 4. Generate candidate and recruiter feed posts using the accepted friends and applicants above.
  const feedPosts = buildFeedPosts(
    ctx,
    joinedAt,
    hiringPostCreatedAt,
    applications,
    friends,
  );

  // 5. Pair buyers with services, price services, save extra services, and build contracts/wallets.
  const { serviceTerms, savedJobs, work } = buildServicesAndContracts(
    ctx,
    joinedAt,
    serviceCreatedAt,
  );

  // 6. Create direct-message rooms from applications, peer connections, and contract chat lines.
  const chats = buildChats(ctx, applications, connections, work.chatLines);

  return {
    openings,
    joinedAt,
    hiringPostCreatedAt,
    serviceCreatedAt,
    connections,
    applications,
    feedPosts,
    serviceTerms,
    proposals: work.proposals,
    contracts: work.contracts,
    wallets: work.wallets,
    ledger: work.ledger,
    savedJobs,
    chats,
  };
}

function createActivityContext(input: ActivityInput): ActivityContext {
  const { now, related } = input;
  return {
    input,
    random: randomGenerator(input.seed ?? 2026),
    now,
    related,
    people: new Map(input.people.map((person) => [person.id, person])),
    candidates: input.people.filter((person) => person.kind === 'candidate'),
    recruiters: input.people.filter((person) => person.kind === 'recruiter'),
    postById: new Map(input.hiringPosts.map((post) => [post.id, post])),
    title: (code: string | null) =>
      code ? input.occupationTitle(code) : 'professional',
    ago: (days: number) => new Date(now.getTime() - days * DAY),
  };
}
