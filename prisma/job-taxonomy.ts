export interface TaxonomyPlan {
  categoriesToCreate: string[];
  subcategoriesToCreate: number;
  jobMoves: Array<{ from: string; to: string; jobs: number }>;
  emptyLegacySubcategoriesToDelete: string[];
  emptyLegacyCategoriesToDelete: string[];
  /** Old subcategories with jobs and no known destination: left untouched for a person to decide. */
  unmapped: Array<{ category: string; subcategory: string; jobs: number }>;
}

type Db = Pick<PrismaClient, 'category' | 'subcategory' | 'job'>;

/**
 * Bring the job categories in line with the taxonomy. Without `apply` it only reports what it would do.
 * Matching is by name, so running it again changes nothing. Jobs are moved, never deleted.
 */
export async function syncJobTaxonomy(
  db: Db,
  taxonomy: JobTaxonomy,
  { apply }: { apply: boolean },
): Promise<TaxonomyPlan> {
  const wanted = new Map(
    taxonomy.categories.map((category) => [
      category.name,
      new Set(category.subcategories.map((sub) => sub.name)),
    ]),
  );
  const existing = await db.category.findMany({
    include: {
      subcategories: { include: { _count: { select: { jobs: true } } } },
    },
  });
  const byName = new Map(existing.map((category) => [category.name, category]));
  const plan: TaxonomyPlan = {
    categoriesToCreate: taxonomy.categories
      .map((category) => category.name)
      .filter((name) => !byName.has(name)),
    subcategoriesToCreate: 0,
    jobMoves: [],
    emptyLegacySubcategoriesToDelete: [],
    emptyLegacyCategoriesToDelete: [],
    unmapped: [],
  };
  for (const category of taxonomy.categories) {
    const have = new Set(
      byName.get(category.name)?.subcategories.map((sub) => sub.name) ?? [],
    );
    plan.subcategoriesToCreate += category.subcategories.filter(
      (sub) => !have.has(sub.name),
    ).length;
  }

  // Subcategories that are not part of the taxonomy are legacy ones.
  const legacy = existing.flatMap((category) =>
    category.subcategories
      .filter((sub) => !wanted.get(category.name)?.has(sub.name))
      .map((sub) => ({ category, sub })),
  );
  for (const { category, sub } of legacy) {
    const destination = LEGACY_SUBCATEGORIES[sub.name];
    if (sub._count.jobs === 0) {
      plan.emptyLegacySubcategoriesToDelete.push(
        `${category.name} / ${sub.name}`,
      );
    } else if (destination) {
      plan.jobMoves.push({
        from: `${category.name} / ${sub.name}`,
        to: destination.join(' / '),
        jobs: sub._count.jobs,
      });
      plan.emptyLegacySubcategoriesToDelete.push(
        `${category.name} / ${sub.name}`,
      );
    } else {
      plan.unmapped.push({
        category: category.name,
        subcategory: sub.name,
        jobs: sub._count.jobs,
      });
    }
  }
  const keptLegacy = new Set(plan.unmapped.map((item) => item.category));
  plan.emptyLegacyCategoriesToDelete = existing
    .filter(
      (category) =>
        !wanted.has(category.name) && !keptLegacy.has(category.name),
    )
    .map((category) => category.name);

  if (!apply) {
    return plan;
  }

  // 1. Create missing categories and subcategories.
  for (const category of taxonomy.categories) {
    const row =
      byName.get(category.name) ??
      (await db.category.create({ data: { name: category.name } }));
    const have = new Set(
      byName.get(category.name)?.subcategories.map((sub) => sub.name) ?? [],
    );
    const missing = category.subcategories.filter((sub) => !have.has(sub.name));
    if (missing.length) {
      await db.subcategory.createMany({
        data: missing.map((sub) => ({ name: sub.name, categoryId: row.id })),
      });
    }
  }
  // 2. Move jobs out of mapped legacy subcategories, then remove the emptied legacy rows.
  const fresh = await db.category.findMany({
    include: { subcategories: true },
  });
  const target = (categoryName: string, subName: string) =>
    fresh
      .find((category) => category.name === categoryName)
      ?.subcategories.find((sub) => sub.name === subName);
  for (const { sub } of legacy) {
    const destination = LEGACY_SUBCATEGORIES[sub.name];
    if (sub._count.jobs > 0 && !destination) {
      continue;
    }
    if (destination) {
      const to = target(...destination);
      if (!to)
        throw new Error(`Missing destination ${destination.join(' / ')}`);
      await db.job.updateMany({
        where: { subcategoryId: sub.id },
        data: { subcategoryId: to.id },
      });
    }
    await db.subcategory.delete({ where: { id: sub.id } });
  }
  for (const name of plan.emptyLegacyCategoriesToDelete) {
    const category = byName.get(name);
    if (category) await db.category.delete({ where: { id: category.id } });
  }
  return plan;
}
