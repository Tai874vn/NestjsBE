/**
 * Prisma taxonomy helpers for loading JobAura's 37 career fields and ISCO-08 subcategories.
 * Exports `loadJobTaxonomy()`, `LEGACY_SUBCATEGORIES`, and `syncJobTaxonomy()` to plan or apply category updates and move jobs out of old subcategories.
 *
 * Calls: prisma/taxonomy/job-taxonomy.json; prisma.category; prisma.subcategory; prisma.job
 * Used by:
 *   - prisma/seed.ts
 *   - prisma/sync-job-taxonomy.ts
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { PrismaClient } from '@prisma/client';

/**
 * JobAura's job categories: the 37 career fields, each with its ISCO-08 unit groups as subcategories.
 * Generated by AIService experiments/skills/build_job_taxonomy.py, so categories, the skill dictionary,
 * and the seniority model use the same fields.
 */
export interface JobTaxonomy {
  format: string;
  categories: Array<{
    name: string;
    subcategories: Array<{ name: string; isco: string }>;
  }>;
}

export function loadJobTaxonomy(): JobTaxonomy {
  return JSON.parse(
    readFileSync(join(__dirname, 'taxonomy', 'job-taxonomy.json'), 'utf-8'),
  ) as JobTaxonomy;
}

